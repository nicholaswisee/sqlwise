import type { WorkspaceDTO } from "../workspace/types";

export type Draft = {
  id: string;
  database_id: string;
  title: string;
  sql: string;
  sql_down: string;
  irreversible: boolean;
  irreversible_reason: string;
  definition_hash: string;
  executed: boolean;
  sql_hash: string;
  dialect: string;
  revision: number;
  applied_version: number;
  last_status: string;
  created_by_name: string;
  created_at: string;
  updated_by_name: string;
  updated_at: string;
};
export type Attempt = {
  id: string;
  sequence: number;
  database_id: string;
  migration_id: string;
  migration_title: string;
  operation: Operation;
  request_id?: string;
  cancels_execution_id?: string;
  draft_revision: number;
  candidate_version: number;
  applied_version: number;
  sql: string;
  sql_hash: string;
  dialect: string;
  statement_count: number;
  executor_name: string;
  status: string;
  error?: string;
  failed_statement?: number;
  started_at: string;
  finished_at?: string | null;
  reconciled_at?: string | null;
};
export type History = {
  workspace: WorkspaceDTO;
  current_version: number;
  drafts: Draft[];
  attempts: Attempt[];
  committed: Attempt[];
  head: Head;
};
export type Detail = {
  workspace: WorkspaceDTO;
  current_version: number;
  draft: Draft;
  attempts: Attempt[];
  requests: Request[];
  eligible: Operation[];
  head: Head;
  blocked: string;
  blocked_by?: Attempt | null;
};
export type Proposal = {
  schema: string;
  source_fingerprint: string;
  warnings: string[];
  sql: string;
  requires_review: boolean;
  changes: { text: string; destructive: boolean }[];
};
export type Operation = "up" | "rollback" | "forward";
export type Head = {
  active: { migration_id: string; execution_id: string }[];
  pending: { migration_id: string; execution_id: string }[];
};
export type Approval = {
  group_id: string;
  group_name: string;
  permission: string;
  leader_name: string;
  leader_active: boolean;
  decision: "" | "approved" | "rejected";
  decided_by?: string;
  decided_at?: string | null;
  can_decide: boolean;
};
export type Request = {
  id: string;
  migration_id: string;
  migration_title: string;
  operation: Operation;
  definition_revision: number;
  definition_hash: string;
  expected_version: number;
  cancels_execution_id?: string;
  requested_by_name: string;
  status: "draft" | "pending_review" | "approved" | "rejected" | "queued";
  review_round: number;
  stale?: string;
  execution_id?: string;
  approvals: Approval[];
  execution: Attempt | null;
  created_at: string;
  updated_at: string;
};
export type Job = {
  job_id: string;
  request_id: string;
  execution_id: string;
  status: "queued" | "running" | "succeeded" | "failed";
  error?: string;
};
