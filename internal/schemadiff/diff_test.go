func ptr(s string) *string { return &s }

func live() Snapshot {
	return Snapshot{Dialect: PostgreSQL, Schema: "public", Tables: []Table{
		{Name: "users", PrimaryKey: []string{"id"}, Columns: []Column{
			{Name: "id", Type: "bigint", Nullable: false},
			{Name: "email", Type: "character varying(255)", Nullable: false},
			{Name: "created_at", Type: "timestamp with time zone", Nullable: false, Default: ptr("now()")},
			{Name: "active", Type: "boolean", Nullable: false, Default: ptr("true")},
			{Name: "nickname", Type: "text", Nullable: true, Default: ptr("'anon'::text")},
		}, Indexes: []Definition{{Name: "users_email_key", Definition: "CREATE UNIQUE INDEX users_email_key ON public.users USING btree (email)"}}},
		{Name: "audit", Columns: []Column{{Name: "id", Type: "integer", Nullable: false, Default: ptr("nextval('audit_id_seq'::regclass)")}}},
	}}
}

func TestIdenticalSnapshotsProduceEmptyDiff(t *testing.T) {
	desired := live()
	// Aliases, case, spacing, casts and table order are normalized away.
	desired.Tables[0].Columns[0].Type = "INT8"
	desired.Tables[0].Columns[1].Type = "varchar( 255 )"
	desired.Tables[0].Columns[2].Type = "timestamptz"
	desired.Tables[0].Columns[3].Default = ptr("TRUE")
	desired.Tables[0].Columns[4].Default = ptr("'anon'")
	desired.Tables[0].Indexes[0].Definition = "CREATE UNIQUE INDEX users_email_key  ON public.users USING btree (email)"
	slices.Reverse(desired.Tables)
	p, err := Propose(live(), desired)
	if err != nil {
		t.Fatal(err)
	}
	if !p.Empty() || p.SQL != "" || len(p.Warnings) != 0 || p.RequiresReview || p.SourceFingerprint != p.DesiredFingerprint {
		t.Fatalf("identical proposal = %+v", p)
	}
}

func TestAddedTablesAndColumnsGenerateSQL(t *testing.T) {
	desired := live()
	desired.Tables[0].Columns = append(desired.Tables[0].Columns,
		Column{Name: "score", Type: "numeric(10,2)", Nullable: false, Default: ptr("0")},
		Column{Name: "bio", Type: "text", Nullable: true})
	desired.Tables = append(desired.Tables, Table{Name: "posts", PrimaryKey: []string{"id"}, Columns: []Column{
		{Name: "id", Type: "uuid", Nullable: false, Default: ptr("gen_random_uuid()")},
		{Name: "title", Type: "varchar(200)", Nullable: false},
		{Name: "body", Type: "text", Nullable: true, Default: ptr("'it''s; fine'")},
		{Name: "published", Type: "bool", Nullable: false, Default: ptr("false")},
	}}, Table{Name: "categories", Columns: []Column{{Name: "name", Type: "text", Nullable: false}}})
	p, err := Propose(live(), desired)
	if err != nil {
		t.Fatal(err)
	}
	want := `-- Generated by sqlwise schema diff. Review before executing.
CREATE TABLE "public"."categories" (
    "name" text NOT NULL
);
CREATE TABLE "public"."posts" (
    "id" uuid DEFAULT gen_random_uuid() NOT NULL,
    "title" character varying(200) NOT NULL,
    "body" text DEFAULT 'it''s; fine',
    "published" boolean DEFAULT false NOT NULL,
    PRIMARY KEY ("id")
);
ALTER TABLE "public"."users" ADD COLUMN "score" numeric(10,2) DEFAULT 0 NOT NULL;
ALTER TABLE "public"."users" ADD COLUMN "bio" text;
`
	if p.SQL != want {
		t.Fatalf("SQL =\n%s\nwant\n%s", p.SQL, want)
	}
	if len(p.Warnings) != 0 || p.RequiresReview {
		t.Fatalf("warnings = %q", p.Warnings)
	}
	kinds := []ChangeKind{}
	for _, c := range p.Changes {
		kinds = append(kinds, c.Kind)
	}
	if !slices.Equal(kinds, []ChangeKind{AddTable, AddTable, AddColumn, AddColumn}) {
		t.Fatalf("changes = %v", kinds)
	}
}

func TestRemovedAndAlteredObjectsWarnWithoutSQL(t *testing.T) {
	desired := live()
	desired.Tables = desired.Tables[:1] // audit removed
	users := &desired.Tables[0]
	users.Columns = slices.Delete(users.Columns, 4, 5) // nickname removed
	users.Columns[1].Type = "text"                     // type change
	users.Columns[2].Nullable = true                   // nullability change
	users.Columns[3].Default = ptr("false")            // default change
	users.Columns = append(users.Columns, Column{Name: "display_name", Type: "text", Nullable: true})
	users.PrimaryKey = []string{"id", "email"}
	users.Indexes = nil
	users.Constraints = []Definition{{Name: "email_lower", Definition: "CHECK (email = lower(email))"}}
	p, err := Propose(live(), desired)
	if err != nil {
		t.Fatal(err)
	}
	if p.SQL != "-- Generated by sqlwise schema diff. Review before executing.\nALTER TABLE \"public\".\"users\" ADD COLUMN \"display_name\" text;\n" {
		t.Fatalf("SQL = %q", p.SQL)
	}
	if !p.RequiresReview {
		t.Fatal("warnings must require review")
	}
	for _, fragment := range []string{
		`Destructive: table "audit"`, `Destructive: column "users"."nickname"`,
		`Change type of "users"."email" from character varying(255) to text`,
		`Change "users"."created_at" from NOT NULL to NULL`, `Change default of "users"."active" from true to false`,
		`Change primary key of "users"`, `Remove index "users_email_key"`, `Add constraint "email_lower"`,
		`Columns of "users" were both removed and added`,
	} {
		if !slices.ContainsFunc(p.Warnings, func(w string) bool { return strings.Contains(w, fragment) }) {
			t.Errorf("missing warning %q in %q", fragment, p.Warnings)
		}
	}
	if !strings.HasPrefix(p.Warnings[0], "Destructive") || !strings.HasPrefix(p.Warnings[len(p.Warnings)-1], "Review") {
		t.Errorf("warnings not grouped: %q", p.Warnings)
	}
	// Destructive means applying the change can lose data: dropping tables,
	// columns or indexes, narrowing a type, or replacing an existing key.
	type key struct {
		kind                  ChangeKind
		table, column, object string
	}
	got := map[key]bool{}
	for _, c := range p.Changes {
		got[key{c.Kind, c.Table, c.Column, c.Object}] = c.Destructive
	}
	want := map[key]bool{
		{RemoveTable, "audit", "", ""}:                true,
		{RemoveColumn, "users", "nickname", ""}:       true,
		{AlterType, "users", "email", ""}:             true,
		{AlterNullability, "users", "created_at", ""}: false,
		{AlterDefault, "users", "active", ""}:         false,
		{AddColumn, "users", "display_name", ""}:      false,
		{AlterPrimaryKey, "users", "", ""}:            true,
		{RemoveIndex, "users", "", "users_email_key"}: true,
		{AddConstraint, "users", "", "email_lower"}:   false,
	}
	if !maps.Equal(got, want) {
		t.Errorf("changes = %v, want %v", got, want)
	}
}

func TestUnsupportedAndUnsafeDefinitionsAreNotGenerated(t *testing.T) {
	for _, tc := range []struct {
		name   string
		column Column
	}{
		{"unsafe-default", Column{Name: "x", Type: "text", Nullable: true, Default: ptr("'a'); DROP TABLE users; --")}},
		{"backslash-default", Column{Name: "x", Type: "text", Nullable: true, Default: ptr(`'a\'`)}},
		{"function-default", Column{Name: "x", Type: "integer", Nullable: true, Default: ptr("nextval('s')")}},
		{"type-mismatch-default", Column{Name: "x", Type: "integer", Nullable: true, Default: ptr("true")}},
		{"clock-on-text", Column{Name: "x", Type: "text", Nullable: true, Default: ptr("now()")}},
		{"unsupported-type", Column{Name: "x", Type: "inet", Nullable: true}},
		{"array-type", Column{Name: "x", Type: "integer[]", Nullable: true}},
		{"precision-timestamp", Column{Name: "x", Type: "timestamp(3) with time zone", Nullable: true}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			desired := live()
			desired.Tables[0].Columns = append(desired.Tables[0].Columns, tc.column)
			desired.Tables = append(desired.Tables, Table{Name: "fresh", Columns: []Column{{Name: "ok", Type: "text", Nullable: true}, tc.column}})
			p, err := Propose(live(), desired)
			if err != nil {
				t.Fatal(err)
			}
			if p.SQL != "" {
				t.Fatalf("generated SQL for unsupported definition: %s", p.SQL)
			}
			if len(p.Warnings) != 2 || !p.RequiresReview {
				t.Fatalf("warnings = %q", p.Warnings)
			}
		})
	}
	desired := live()
	desired.Tables[0].Columns = append(desired.Tables[0].Columns, Column{Name: "required", Type: "text", Nullable: false})
	p, err := Propose(live(), desired)
	if err != nil || !strings.Contains(p.SQL, `ADD COLUMN "required" text NOT NULL;`) || len(p.Warnings) != 1 || !strings.Contains(p.Warnings[0], "without a default") {
		t.Fatalf("NOT NULL without default = %+v, %v", p, err)
	}
	desired = live()
	desired.Tables = append(desired.Tables, Table{Name: "indexed", Columns: []Column{{Name: "a", Type: "int", Nullable: true}},
		Indexes: []Definition{{Name: "indexed_a", Definition: "CREATE INDEX indexed_a ON public.indexed (a)"}}})
	if p, _ := Propose(live(), desired); !strings.Contains(p.SQL, `CREATE TABLE "public"."indexed"`) || len(p.Warnings) != 1 {
		t.Fatalf("index on new table = %+v", p)
	}
}

func TestUnusualIdentifiersAreQuoted(t *testing.T) {
	desired := Snapshot{Dialect: PostgreSQL, Schema: `Odd "Schema"`, Tables: []Table{{Name: `Robert"); DROP TABLE x; --`, Columns: []Column{
		{Name: "Mixed Case", Type: "text", Nullable: true}, {Name: "select", Type: "int", Nullable: true}, {Name: "名前", Type: "text", Nullable: true},
	}}}}
	p, err := Propose(Snapshot{Dialect: PostgreSQL, Schema: `Odd "Schema"`}, desired)
	if err != nil {
		t.Fatal(err)
	}
	want := "CREATE TABLE \"Odd \"\"Schema\"\"\".\"Robert\"\"); DROP TABLE x; --\" (\n    \"Mixed Case\" text,\n    \"select\" integer,\n    \"名前\" text\n);"
	if !strings.Contains(p.SQL, want) {
		t.Fatalf("SQL = %s", p.SQL)
	}
}

func TestProposalIsDeterministic(t *testing.T) {
	build := func(reverse bool) Snapshot {
		s := live()
		s.Tables = append(s.Tables, Table{Name: "b", Columns: []Column{{Name: "x", Type: "text", Nullable: true}}},
			Table{Name: "a", Columns: []Column{{Name: "y", Type: "inet", Nullable: true}}})
		s.Tables[0].Constraints = []Definition{{Name: "z", Definition: "CHECK (true)"}, {Name: "y", Definition: "CHECK (false)"}}
		if reverse {
			slices.Reverse(s.Tables)
			slices.Reverse(s.Tables[len(s.Tables)-1].Constraints)
		}
		return s
	}
	first, err := Propose(live(), build(false))
	if err != nil {
		t.Fatal(err)
	}
	for range 20 {
		next, err := Propose(live(), build(true))
		if err != nil {
			t.Fatal(err)
		}
		if next.SQL != first.SQL || !slices.Equal(next.Warnings, first.Warnings) || !slices.Equal(next.Changes, first.Changes) || next.DesiredFingerprint != first.DesiredFingerprint {
			t.Fatalf("nondeterministic proposal:\n%+v\n%+v", first, next)
		}
	}
}

func TestParseDesiredValidation(t *testing.T) {
	valid := `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"id","type":"bigint","nullable":false}],"primaryKey":["id"]}]}`
	if s, err := ParseDesired(valid); err != nil || s.Tables[0].Columns[0].Nullable || s.Tables[0].PrimaryKey[0] != "id" {
		t.Fatalf("valid = %+v, %v", s, err)
	}
	for name, raw := range map[string]string{
		"syntax":            `{"dialect":`,
		"trailing":          valid + `{}`,
		"unknown-field":     `{"dialect":"postgresql","schema":"public","tables":[],"extra":1}`,
		"missing-nullable":  `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"id","type":"int"}]}]}`,
		"dialect":           `{"dialect":"oracle","schema":"public","tables":[]}`,
		"internal-schema":   `{"dialect":"postgresql","schema":"sqlwise_internal","tables":[]}`,
		"catalog":           `{"dialect":"postgresql","schema":"pg_catalog","tables":[]}`,
		"empty-schema":      `{"dialect":"postgresql","schema":"","tables":[]}`,
		"long-identifier":   `{"dialect":"postgresql","schema":"public","tables":[{"name":"` + strings.Repeat("x", 64) + `","columns":[{"name":"a","type":"int","nullable":true}]}]}`,
		"duplicate-table":   `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"a","type":"int","nullable":true}]},{"name":"t","columns":[{"name":"a","type":"int","nullable":true}]}]}`,
		"duplicate-column":  `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"a","type":"int","nullable":true},{"name":"a","type":"int","nullable":true}]}]}`,
		"no-columns":        `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[]}]}`,
		"injected-type":     `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"a","type":"int); DROP TABLE x; --","nullable":true}]}]}`,
		"bad-varchar":       `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"a","type":"varchar(0)","nullable":true}]}]}`,
		"pk-missing-column": `{"dialect":"postgresql","schema":"public","tables":[{"name":"t","columns":[{"name":"a","type":"int","nullable":true}],"primaryKey":["b"]}]}`,
		"too-large":         strings.Repeat(" ", MaxInputBytes+1),
	} {
		t.Run(name, func(t *testing.T) {
			var validation *ValidationError
			if _, err := ParseDesired(raw); !errors.As(err, &validation) {
				t.Fatalf("error = %v, want validation error", err)
			}
		})
	}
	var dialect *UnsupportedDialectError
	if _, err := ParseDesired(`{"dialect":"mysql","schema":"app","tables":[]}`); !errors.As(err, &dialect) {
		t.Fatalf("mysql = %v", err)
	}
	if _, err := Propose(Snapshot{Dialect: MySQL, Schema: "app"}, Snapshot{Dialect: MySQL, Schema: "app"}); !errors.As(err, &dialect) {
		t.Fatalf("mysql generator = %v", err)
	}
	if _, err := Propose(Snapshot{Dialect: PostgreSQL, Schema: "other"}, Snapshot{Dialect: PostgreSQL, Schema: "public"}); err == nil {
		t.Fatal("schema scope mismatch accepted")
	}
}

func TestFingerprintTracksSchemaContent(t *testing.T) {
	a, b := live(), live()
	if a.Fingerprint() != b.Fingerprint() {
		t.Fatal("equal snapshots differ")
	}
	b.Tables[0].Columns[4].Nullable = false
	if a.Fingerprint() == b.Fingerprint() {
		t.Fatal("nullability change kept fingerprint")
	}
	internal := Snapshot{Dialect: PostgreSQL, Schema: InternalSchema, Tables: live().Tables}
	if len(internal.WithoutInternal().Tables) != 0 {
		t.Fatal("internal schema leaked into user snapshot")
	}
}
