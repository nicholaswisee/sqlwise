package schemadiff

import (
	"fmt"
	"slices"
	"strings"
)

// Proposal is a reviewable migration candidate. It is computed on demand and
// never written anywhere by preview.
type Proposal struct {
	Dialect            string
	Schema             string
	SourceFingerprint  string
	DesiredFingerprint string
	Changes            []Change
	SQL                string
	Warnings           []string
	RequiresReview     bool
}

func (p Proposal) Empty() bool { return len(p.Changes) == 0 }

// Propose compares snapshots and generates PostgreSQL CREATE TABLE and ADD
// COLUMN statements for the supported subset. Everything else is reported as a
// warning without SQL.
func Propose(current, desired Snapshot) (Proposal, error) {
	if desired.Dialect != current.Dialect {
		return Proposal{}, invalid("Desired dialect %q does not match the live database (%q).", desired.Dialect, current.Dialect)
	}
	if desired.Dialect != PostgreSQL {
		return Proposal{}, &UnsupportedDialectError{Dialect: desired.Dialect}
	}
	if desired.Schema != current.Schema {
		return Proposal{}, invalid("Desired schema %q does not match the compared schema %q.", desired.Schema, current.Schema)
	}
	current = current.WithoutInternal()
	p := Proposal{Dialect: desired.Dialect, Schema: desired.Schema, SourceFingerprint: current.Fingerprint(),
		DesiredFingerprint: desired.Fingerprint(), Changes: Compare(current, desired)}
	tables := make(map[string]Table, len(desired.Tables))
	for _, t := range desired.Tables {
		tables[t.Name] = t
	}
	var statements []string
	removed, added := make(map[string]bool), make(map[string]bool)
	for _, c := range p.Changes {
		switch c.Kind {
		case AddTable:
			sql, warnings := createTable(desired.Schema, tables[c.Table])
			if sql != "" {
				statements = append(statements, sql)
			}
			p.Warnings = append(p.Warnings, warnings...)
			added[""] = true
		case AddColumn:
			column := findColumn(tables[c.Table], c.Column)
			sql, warning := addColumn(desired.Schema, c.Table, column)
			if sql != "" {
				statements = append(statements, sql)
			}
			if warning != "" {
				p.Warnings = append(p.Warnings, warning)
			}
			added[c.Table] = true
		case RemoveTable:
			p.Warnings = append(p.Warnings, fmt.Sprintf("Destructive: table %s exists only in the live schema. No DROP is generated; write it manually if intended.", QuoteIdent(c.Table)))
			removed[""] = true
		case RemoveColumn:
			p.Warnings = append(p.Warnings, fmt.Sprintf("Destructive: column %s.%s exists only in the live schema. No DROP is generated; write it manually if intended.", QuoteIdent(c.Table), QuoteIdent(c.Column)))
			removed[c.Table] = true
		default:
			p.Warnings = append(p.Warnings, "Unsupported: "+c.String()+". No SQL is generated for this change.")
		}
	}
	// Walk changes again so hints follow the deterministic change order.
	hinted := make(map[string]bool)
	for _, c := range p.Changes {
		scope := c.Table
		if c.Kind == AddTable || c.Kind == RemoveTable {
			scope = ""
		}
		if hinted[scope] || !removed[scope] || !added[scope] {
			continue
		}
		hinted[scope] = true
		where := "Tables were"
		if scope != "" {
			where = "Columns of " + QuoteIdent(scope) + " were"
		}
		p.Warnings = append(p.Warnings, "Review: "+where+" both removed and added. Renames are never inferred; if this is a rename, replace the generated SQL with ALTER ... RENAME.")
	}
	slices.SortStableFunc(p.Warnings, func(a, b string) int { return warningRank(a) - warningRank(b) })
	if len(statements) > 0 {
		p.SQL = "-- Generated by sqlwise schema diff. Review before executing.\n" + strings.Join(statements, "\n") + "\n"
	}
	p.RequiresReview = len(p.Warnings) > 0
	return p, nil
}

func createTable(schema string, t Table) (string, []string) {
	var lines, warnings []string
	name := QuoteIdent(schema) + "." + QuoteIdent(t.Name)
	for _, c := range t.Columns {
		definition, reason := columnDefinition(c)
		if reason != "" {
			return "", []string{fmt.Sprintf("Unsupported: table %s was not generated because column %s %s.", QuoteIdent(t.Name), QuoteIdent(c.Name), reason)}
		}
		lines = append(lines, "    "+definition)
	}
	if len(t.PrimaryKey) > 0 {
		lines = append(lines, "    PRIMARY KEY ("+strings.Join(quoteAll(t.PrimaryKey), ", ")+")")
	}
	for _, d := range t.Indexes {
		warnings = append(warnings, fmt.Sprintf("Unsupported: index %s on new table %s is not generated.", QuoteIdent(d.Name), QuoteIdent(t.Name)))
	}
	for _, d := range t.Constraints {
		warnings = append(warnings, fmt.Sprintf("Unsupported: constraint %s on new table %s is not generated.", QuoteIdent(d.Name), QuoteIdent(t.Name)))
	}
	return "CREATE TABLE " + name + " (\n" + strings.Join(lines, ",\n") + "\n);", warnings
}

func addColumn(schema, table string, c Column) (string, string) {
	definition, reason := columnDefinition(c)
	if reason != "" {
		return "", fmt.Sprintf("Unsupported: column %s.%s was not generated because it %s.", QuoteIdent(table), QuoteIdent(c.Name), reason)
	}
	sql := "ALTER TABLE " + QuoteIdent(schema) + "." + QuoteIdent(table) + " ADD COLUMN " + definition + ";"
	if !c.Nullable && c.Default == nil {
		return sql, fmt.Sprintf("Review: adding NOT NULL column %s.%s without a default fails if the table already has rows.", QuoteIdent(table), QuoteIdent(c.Name))
	}
	return sql, ""
}

// columnDefinition renders a column from the validated subset; reason
// explains why a column cannot be generated.
func columnDefinition(c Column) (string, string) {
	typ, ok := parseType(c.Type)
	if !ok || !typ.supported {
		return "", fmt.Sprintf("uses type %q outside the supported subset", c.Type)
	}
	definition := QuoteIdent(c.Name) + " " + typ.canonical
	if c.Default != nil {
		d := parseDefault(*c.Default, typ)
		if !d.supported {
			return "", fmt.Sprintf("has a default expression %q outside the supported subset", *c.Default)
		}
		if d.canonical != "NULL" {
			definition += " DEFAULT " + d.canonical
		}
	}
	if !c.Nullable {
		definition += " NOT NULL"
	}
	return definition, ""
}

func findColumn(t Table, name string) Column {
	for _, c := range t.Columns {
		if c.Name == name {
			return c
		}
	}
	return Column{}
}

// warningRank orders destructive, then unsupported, then review notes.
func warningRank(w string) int {
	switch {
	case strings.HasPrefix(w, "Destructive"):
		return 0
	case strings.HasPrefix(w, "Unsupported"):
		return 1
	}
	return 2
}
